// Builds src/words/*.ts from scripts/answers.txt (hand-picked everyday words,
// the ones a round can ask for) and a general English dictionary (everything
// a player is allowed to type as a guess).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const here = new URL('.', import.meta.url);
const dictionary = createRequire(import.meta.url)('an-array-of-english-words');

const five = /^[a-z]{5}$/;
const answers = [...new Set(readFileSync(new URL('answers.txt', here), 'utf8').split(/\s+/).filter(Boolean))].sort();

const bad = answers.filter((w) => !five.test(w));
if (bad.length) throw new Error(`Not five letters: ${bad.join(', ')}`);

const known = new Set(dictionary.filter((w) => five.test(w)));
const unknown = answers.filter((w) => !known.has(w));
if (unknown.length) console.warn(`Not in the dictionary (kept anyway): ${unknown.join(', ')}`);

const allowed = [...new Set([...known, ...answers])].sort();
const header = '// Generated by `npm run words`. Edit scripts/answers.txt instead.\n';

writeFileSync(
  new URL('../src/words/answers.ts', here),
  `${header}export const ANSWERS: readonly string[] = '${answers.join(' ')}'.split(' ');\n`,
);
writeFileSync(
  new URL('../src/words/allowed.ts', here),
  `${header}export const ALLOWED: ReadonlySet<string> = new Set('${allowed.join('')}'.match(/.{5}/g));\n`,
);
console.log(`${answers.length} answers, ${allowed.length} allowed guesses`);
