// Builds src/words/*.ts.
//  - Answers (words a round can ask for): 5 letters come from the hand-picked
//    scripts/answers.txt; other lengths from the most common tiers of SCOWL
//    (wordlist-english), minus plurals and scripts/blocked.txt.
//  - Allowed guesses: a general English dictionary (an-array-of-english-words).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const here = new URL('.', import.meta.url);
const require = createRequire(import.meta.url);
const dictionary = require('an-array-of-english-words');
const scowl = require('wordlist-english');

export const LENGTHS = [3, 4, 5, 6, 7, 8];
const words = (file) => readFileSync(new URL(file, here), 'utf8').split(/\s+/).filter(Boolean);
const blocked = new Set(words('blocked.txt'));
const plain = (w) => /^[a-z]+$/.test(w) && !blocked.has(w);
const plural = (w) => w.endsWith('s') && !w.endsWith('ss');

const common = [...scowl['english/10'], ...scowl['english/20']];
const answers = {};
for (const n of LENGTHS) {
  const pool = n === 5 ? words('answers.txt') : common.filter((w) => w.length === n && !plural(w));
  answers[n] = [...new Set(pool.filter((w) => plain(w) && w.length === n))].sort();
}

const allowed = {};
for (const n of LENGTHS) {
  const set = new Set(dictionary.filter((w) => w.length === n && /^[a-z]+$/.test(w)));
  for (const w of answers[n]) set.add(w);
  allowed[n] = [...set].sort();
}

const header = '// Generated by `npm run words`. Edit scripts/*.txt instead.\n';
const table = (lists) =>
  `{\n${LENGTHS.map((n) => `  ${n}: '${lists[n].join('')}',`).join('\n')}\n}`;

writeFileSync(
  new URL('../src/words/answers.ts', here),
  `${header}const PACKED: Record<number, string> = ${table(answers)};\n\n` +
    `/** Words a round can ask for, by length. */\n` +
    `export const ANSWERS: Record<number, readonly string[]> = Object.fromEntries(\n` +
    `  Object.entries(PACKED).map(([n, s]) => [n, s.match(new RegExp(\`.{\${n}}\`, 'g')) ?? []]),\n);\n`,
);
writeFileSync(
  new URL('../src/words/allowed.ts', here),
  `${header}const PACKED: Record<number, string> = ${table(allowed)};\n\n` +
    `/** Every word a player may guess, by length. */\n` +
    `export const ALLOWED: Record<number, ReadonlySet<string>> = Object.fromEntries(\n` +
    `  Object.entries(PACKED).map(([n, s]) => [n, new Set(s.match(new RegExp(\`.{\${n}}\`, 'g')))]),\n);\n`,
);
console.log(LENGTHS.map((n) => `${n}: ${answers[n].length} answers / ${allowed[n].length} allowed`).join('\n'));
